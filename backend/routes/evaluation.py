from fastapi import APIRouter, HTTPException, Depends
from pydantic import BaseModel
from services.evaluation_service import evaluation_service
from utils.responses import success_response, error_response
from middleware.auth import verify_token

router = APIRouter()

class EvaluationRequest(BaseModel):
    """
    Request model for triggering a session evaluation.
    The session_id must match the one generated by React and used by Unity.
    """
    session_id: str

@router.post("/evaluate")
async def evaluate_session(request: EvaluationRequest, user=Depends(verify_token)):
    """
    Evaluates a simulation session based on the transcript stored in Firestore.
    
    FLOW:
    1. React clicks 'Finish' -> Sends session_id here.
    2. Backend fetches transcript from: 
       /artifacts/sdgp-careerverse-2026/public/data/sessions/{session_id}
    3. Gemini analyzes the 'transcript' array.
    4. Results are saved to 'scores' collection and returned to React.
    """
    try:
        # Attempt to perform a real evaluation using the transcript in Firestore
        # The service now uses the synchronized 'sdgp-careerverse-2026' app_id
        result = await evaluation_service.evaluate_session(request.session_id)
        
        return success_response(
            data=result, 
            message="Performance analysis complete. Results persisted to Firestore."
        )

    except ValueError as ve:
        # --- DUMMY FALLBACK FOR END-TO-END UI TESTING ---
        # This triggers if the 'transcript' field is missing or the document hasn't synced yet.
        print(f"DEBUG: Session {request.session_id} transcript not found. Providing mock data.")
        
        dummy_data = {
            "scores": {
                "communication": 85,
                "empathy": 92,
                "problem_solving": 78,
                "classroom_management": 84,
                "total_score": 85
            },
            "feedback": "Excellent rapport building. You identified student needs quickly but could improve your closing firmess.",
            "summary": "High pedagogical aptitude detected.",
            "simulation_type": "teacher",
            "session_id": request.session_id
        }
        return success_response(
            data=dummy_data, 
            message="Fallback generated: Ensure Unity is successfully sending chat logs to the backend."
        )

    except Exception as e:
        print(f"CRITICAL ERROR in Evaluation Route: {str(e)}")
        return error_response(
            message=f"Evaluation Engine Error: {str(e)}", 
            code=500
        )